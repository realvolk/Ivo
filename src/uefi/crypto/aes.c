static const uint8_t rcon[10] = {
    0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

static uint32_t sub_word(uint32_t w) {
    return ((uint32_t)sbox[(w >> 24) & 0xff] << 24)
         | ((uint32_t)sbox[(w >> 16) & 0xff] << 16)
         | ((uint32_t)sbox[(w >>  8) & 0xff] <<  8)
         |  (uint32_t)sbox[ w        & 0xff];
}

static uint32_t rot_word(uint32_t w) {
    return (w << 8) | (w >> 24);
}

static uint8_t xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0x00));
}

static uint8_t mul3(uint8_t x) {
    return xtime(x) ^ x;
}

static uint8_t gmul(uint8_t x, uint8_t y) {
    uint8_t r = 0;
    while (y) {
        if (y & 1) r ^= x;
        x = xtime(x);
        y >>= 1;
    }
    return r;
}

/* Four tables for the GF constants inv_mix_columns multiplies by.
 * Built once at aes_init time so each round is four lookups per
 * column instead of a bit-by-bit multiply. */
static uint8_t gmul_table[4][256];
static int     gmul_tables_ready;

static void gmul_tables_init(void) {
    if (gmul_tables_ready) return;
    static const uint8_t constants[4] = { 14, 11, 13, 9 };
    for (int k = 0; k < 4; k++) {
        for (int x = 0; x < 256; x++) {
            gmul_table[k][x] = gmul((uint8_t)x, constants[k]);
        }
    }
    gmul_tables_ready = 1;
}

static void add_round_key(uint8_t state[16], const uint32_t *w, int round) {
    for (int i = 0; i < 4; i++) {
        state[4*i]     ^= (uint8_t)(w[round*4 + i] >> 24);
        state[4*i + 1] ^= (uint8_t)(w[round*4 + i] >> 16);
        state[4*i + 2] ^= (uint8_t)(w[round*4 + i] >>  8);
        state[4*i + 3] ^= (uint8_t)(w[round*4 + i]);
    }
}

static void sub_bytes(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = sbox[state[i]];
}

static void inv_sub_bytes(uint8_t state[16]) {
    for (int i = 0; i < 16; i++) state[i] = inv_sbox[state[i]];
}

static void shift_rows(uint8_t state[16]) {
    uint8_t t;
    t = state[1];  state[1]  = state[5];  state[5]  = state[9];
    state[9]  = state[13]; state[13] = t;
    t = state[2];  state[2]  = state[10]; state[10] = t;
    t = state[6];  state[6]  = state[14]; state[14] = t;
    t = state[15]; state[15] = state[11]; state[11] = state[7];
    state[7]  = state[3];  state[3]  = t;
}

static void inv_shift_rows(uint8_t state[16]) {
    uint8_t t;
    t = state[13]; state[13] = state[9];  state[9]  = state[5];
    state[5]  = state[1];  state[1]  = t;
    t = state[2];  state[2]  = state[10]; state[10] = t;
    t = state[6];  state[6]  = state[14]; state[14] = t;
    t = state[3];  state[3]  = state[7];  state[7]  = state[11];
    state[11] = state[15]; state[15] = t;
}

static void mix_columns(uint8_t state[16]) {
    for (int i = 0; i < 4; i++) {
        uint8_t a = state[4*i];
        uint8_t b = state[4*i + 1];
        uint8_t c = state[4*i + 2];
        uint8_t d = state[4*i + 3];
        state[4*i]     = xtime(a) ^ mul3(b) ^ c       ^ d;
        state[4*i + 1] = a       ^ xtime(b) ^ mul3(c) ^ d;
        state[4*i + 2] = a       ^ b       ^ xtime(c) ^ mul3(d);
        state[4*i + 3] = mul3(a) ^ b       ^ c       ^ xtime(d);
    }
}

static void inv_mix_columns(uint8_t state[16]) {
    for (int i = 0; i < 4; i++) {
        uint8_t a = state[4*i];
        uint8_t b = state[4*i + 1];
        uint8_t c = state[4*i + 2];
        uint8_t d = state[4*i + 3];
        state[4*i]     = gmul_table[0][a] ^ gmul_table[1][b] ^
                         gmul_table[2][c] ^ gmul_table[3][d];
        state[4*i + 1] = gmul_table[3][a] ^ gmul_table[0][b] ^
                         gmul_table[1][c] ^ gmul_table[2][d];
        state[4*i + 2] = gmul_table[2][a] ^ gmul_table[3][b] ^
                         gmul_table[0][c] ^ gmul_table[1][d];
        state[4*i + 3] = gmul_table[1][a] ^ gmul_table[2][b] ^
                         gmul_table[3][c] ^ gmul_table[0][d];
    }
}

int aes_init(struct aes_ctx *ctx, const uint8_t *key, size_t key_len) {
    if (!ctx || !key) return -1;
    int nk, nr;

    gmul_tables_init();

    switch (key_len) {
        case AES128_KEY_SIZE: nk = 4; nr = 10; break;
        case AES256_KEY_SIZE: nk = 8; nr = 14; break;
        default:
            if (ctx) ivo_wipe(ctx, sizeof(*ctx));
            return -1;
    }

    ctx->nr = nr;
    memset(ctx->rk, 0, sizeof(ctx->rk));

    for (int i = 0; i < nk; i++) {
        ctx->rk[i] = ((uint32_t)key[4*i]     << 24)
                   | ((uint32_t)key[4*i + 1] << 16)
                   | ((uint32_t)key[4*i + 2] <<  8)
                   |  (uint32_t)key[4*i + 3];
    }

    for (int i = nk; i < 4 * (nr + 1); i++) {
        uint32_t temp = ctx->rk[i - 1];
        if (i % nk == 0)
            temp = sub_word(rot_word(temp)) ^ ((uint32_t)rcon[i/nk - 1] << 24);
        else if (nk > 6 && i % nk == 4)
            temp = sub_word(temp);
        ctx->rk[i] = ctx->rk[i - nk] ^ temp;
    }

    return 0;
}

void aes_encrypt_block(const struct aes_ctx *ctx,
                       const uint8_t in[AES_BLOCK_SIZE],
                       uint8_t out[AES_BLOCK_SIZE]) {
    if (!ctx || !in || !out) return;
    uint8_t state[16];
    int round;

    memcpy(state, in, 16);
    add_round_key(state, ctx->rk, 0);

    for (round = 1; round < ctx->nr; round++) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, ctx->rk, round);
    }

    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, ctx->rk, ctx->nr);

    memcpy(out, state, 16);
}

void aes_decrypt_block(const struct aes_ctx *ctx,
                       const uint8_t in[AES_BLOCK_SIZE],
                       uint8_t out[AES_BLOCK_SIZE]) {
    if (!ctx || !in || !out) return;
    uint8_t state[16];
    int round;

    memcpy(state, in, 16);
    add_round_key(state, ctx->rk, ctx->nr);

    for (round = ctx->nr - 1; round >= 1; round--) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, ctx->rk, round);
        inv_mix_columns(state);
    }

    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, ctx->rk, 0);

    memcpy(out, state, 16);
}

void aes_clear(struct aes_ctx *ctx) {
    if (ctx) ivo_wipe(ctx, sizeof(*ctx));
}

void aes_cfb128_encrypt(struct aes_ctx *ctx,
                        const uint8_t iv[AES_BLOCK_SIZE],
                        const uint8_t *in, uint8_t *out, size_t len)
{
    uint8_t feedback[AES_BLOCK_SIZE];
    uint8_t keystream[AES_BLOCK_SIZE];
    memcpy(feedback, iv, AES_BLOCK_SIZE);

    size_t block = 0;
    for (size_t i = 0; i < len; i++) {
        if ((i % AES_BLOCK_SIZE) == 0) {
            aes_encrypt_block(ctx, feedback, keystream);
            block = i;
        }
        uint8_t ks = keystream[i - block];
        out[i] = in[i] ^ ks;
        feedback[i - block] = out[i];
    }
}