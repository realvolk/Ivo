/*
 * Build-time only. Validates the config with the same parser the
 * bootloader uses, then writes the raw bytes as a C string literal.
 *
 * Usage: mkinitivo --config FILE --output FILE
 *
 * Not wired into the build.
 */

#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#include "config.h"
#include "ivo-util.h"

/* config_parse allocates entry strings via mm_alloc. */
void *mm_alloc(size_t size) { return malloc(size); }
void  mm_free(void *ptr)    { free(ptr); }

static void emit_c_string(ivo_buf_t *out, const char *s, size_t n)
{
    ivo_buf_puts(out, "\"");
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        switch (c) {
        case '\\': ivo_buf_puts(out, "\\\\"); break;
        case '"':  ivo_buf_puts(out, "\\\""); break;
        case '\n': ivo_buf_puts(out, "\\n\"\n    \""); break;
        case '\t': ivo_buf_puts(out, "\\t");  break;
        case '\r': ivo_buf_puts(out, "\\r");  break;
        /* "??/" and friends are trigraphs under -std=c11. */
        case '?':  ivo_buf_puts(out, "\\?");  break;
        default:
            if (c < 0x20 || c > 0x7E) ivo_buf_printf(out, "\\%03o", c);
            else ivo_buf_append(out, (const char *)&c, 1);
        }
    }
    ivo_buf_puts(out, "\"");
}

int main(int argc, char **argv)
{
    const char *config_path = 0;
    const char *output_path = 0;

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--config") == 0 && i + 1 < argc) {
            config_path = argv[++i];
        } else if (strcmp(argv[i], "--output") == 0 && i + 1 < argc) {
            output_path = argv[++i];
        } else {
            fprintf(stderr,
                    "usage: mkinitivo --config FILE --output FILE\n");
            return 1;
        }
    }
    if (!config_path || !output_path) {
        fprintf(stderr,
                "usage: mkinitivo --config FILE --output FILE\n");
        return 1;
    }

    uint8_t *content = 0;
    size_t len = 0;
    if (ivo_read_file(config_path, 1 << 20, &content, &len) != 0) {
        fprintf(stderr, "mkinitivo: %s: %s\n", config_path, strerror(errno));
        return 1;
    }

    if (config_parse((const char *)content, len) != 0) {
        fprintf(stderr, "mkinitivo: %s:%d: parse failed\n", config_path,
                config_error_line());
        free(content);
        return 1;
    }

    ivo_buf_t out = {0};
    ivo_buf_puts(&out, "/* Generated by tools/mkinitivo. Do not edit. */\n"
                       "#ifndef EMBEDDED_CONFIG_H\n"
                       "#define EMBEDDED_CONFIG_H\n\n"
                       "static const char ivo_embedded_config[] =\n    ");
    emit_c_string(&out, (const char *)content, len);
    ivo_buf_puts(&out, ";\n\n#endif\n");
    free(content);

    if (out.failed ||
        ivo_write_file(output_path, out.p, out.len, 0644, IVO_WRITE_KEEP_MODE) != 0) {
        fprintf(stderr, "mkinitivo: %s: %s\n", output_path,
                out.failed ? "out of memory" : strerror(errno));
        ivo_buf_free(&out);
        return 1;
    }
    ivo_buf_free(&out);
    return 0;
}
