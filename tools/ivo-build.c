/*
 *   ivo-build font INPUT.ttf LINE_HEIGHT BASELINE OUT.h
 *   ivo-build mkinitivo --config FILE --output FILE
 */

#define _GNU_SOURCE
#include <errno.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define STB_TRUETYPE_IMPLEMENTATION
#include "third_party/stb_truetype.h"

#include "config.h"
#include "ivo-util.h"

void *mm_alloc(size_t size) { return malloc(size); }
void  mm_free(void *ptr)    { free(ptr); }

static const int FIRST_CHAR = 0x20;
static const int LAST_CHAR  = 0x7E;

struct glyph_out {
    uint32_t off;
    uint8_t  w;
    uint8_t  height;
    uint8_t  advance;
    int8_t   bx;
    int8_t   by;
};

static int cmd_font(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: ivo-build font FONT.ttf LINE_HEIGHT BASELINE OUT.h\n");
        return 1;
    }
    const char *ttf_path = argv[0];
    int line_height      = atoi(argv[1]);
    int baseline         = atoi(argv[2]);
    const char *out_path = argv[3];

    FILE *f = fopen(ttf_path, "rb");
    if (!f) { perror(ttf_path); return 1; }
    fseek(f, 0, SEEK_END);
    long ttf_size = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *ttf = malloc((size_t)ttf_size);
    if (!ttf) { fclose(f); return 1; }
    if (fread(ttf, 1, (size_t)ttf_size, f) != (size_t)ttf_size) {
        fclose(f); free(ttf); return 1;
    }
    fclose(f);

    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, ttf, 0)) {
        fprintf(stderr, "InitFont failed\n");
        free(ttf);
        return 1;
    }

    float scale = stbtt_ScaleForPixelHeight(&info, (float)baseline);

    int count = LAST_CHAR - FIRST_CHAR + 1;
    struct glyph_out *glyphs = calloc(count, sizeof(*glyphs));
    uint8_t **bufs = calloc(count, sizeof(*bufs));
    int *buf_sizes = calloc(count, sizeof(*buf_sizes));
    int adv_ref = 0, lsb_ref = 0;
    stbtt_GetCodepointHMetrics(&info, 'M', &adv_ref, &lsb_ref);
    int advance_px = (int)(adv_ref * scale + 0.5f);
    if (advance_px < 1) advance_px = 1;
    if (advance_px > 255) advance_px = 255;
    int cell_w = advance_px;

    uint32_t total = 0;
    for (int i = 0; i < count; i++) {
        int cp = FIRST_CHAR + i;
        int x0, y0, x1, y1;
        stbtt_GetCodepointBitmapBox(&info, cp, scale, scale, &x0, &y0, &x1, &y1);
        int bw = x1 - x0;
        int bh = y1 - y0;
        if (bw < 0) bw = 0;
        if (bh < 0) bh = 0;

        glyphs[i].w       = (uint8_t)cell_w;
        glyphs[i].height  = (uint8_t)line_height;
        glyphs[i].bx      = 0;
        glyphs[i].by      = 0;
        glyphs[i].advance = (uint8_t)(advance_px * 4);
        glyphs[i].off     = total;

        size_t bytes = (size_t)line_height * cell_w;
        buf_sizes[i] = (int)bytes;
        bufs[i] = calloc(1, bytes);
        if (!bufs[i]) return 1;

        unsigned char *bmp = stbtt_GetCodepointBitmap(&info, scale, scale, cp,
                                                       &bw, &bh, 0, 0);
        if (bmp) {
            for (int r = 0; r < line_height; r++) {
                int src_r = r - baseline - y0;
                if (src_r < 0 || src_r >= bh) continue;
                for (int c = 0; c < bw; c++) {
                    int dst_c = c + x0;
                    if (dst_c < 0 || dst_c >= cell_w) continue;
                    bufs[i][(size_t)r * cell_w + dst_c] = bmp[src_r * bw + c];
                }
            }
            stbtt_FreeBitmap(bmp, 0);
        }
        total += (uint32_t)bytes;
    }

    FILE *out = fopen(out_path, "w");
    if (!out) { perror(out_path); return 1; }
    fprintf(out, "/* Generated by tools/ivo-build font. Do not edit. */\n");
    fprintf(out, "#ifndef IVO_FONT_DATA_H\n#define IVO_FONT_DATA_H\n");
    fprintf(out, "#include \"ui/font.h\"\n\n");
    fprintf(out, "#define FONT_HEIGHT %d\n", line_height);
    fprintf(out, "#define FONT_BASELINE %d\n", baseline);
    fprintf(out, "#define FONT_FIRST_CHAR 0x%02X\n", FIRST_CHAR);
    fprintf(out, "#define FONT_GLYPH_COUNT %d\n\n", count);

    fprintf(out, "static const uint8_t font_data_raw[] = {\n");
    for (int i = 0; i < count; i++) {
        if (!bufs[i]) continue;
        for (int b = 0; b < buf_sizes[i]; b++) {
            if ((b % 16) == 0) fprintf(out, "    ");
            fprintf(out, "0x%02X,", bufs[i][b]);
            if ((b % 16) == 15) fprintf(out, "\n");
            else fprintf(out, " ");
        }
        if (buf_sizes[i] % 16) fprintf(out, "\n");
    }
    fprintf(out, "};\n\n");

    fprintf(out, "static const struct font_glyph font_glyphs_raw[] = {\n");
    for (int i = 0; i < count; i++) {
        fprintf(out, "    { %uu, %u, %u, %u, %d, %d },\n",
                glyphs[i].off, glyphs[i].w, glyphs[i].height,
                glyphs[i].advance, (int)glyphs[i].bx, (int)glyphs[i].by);
    }
    fprintf(out, "};\n\n#endif\n");
    fclose(out);

    for (int i = 0; i < count; i++) free(bufs[i]);
    free(bufs); free(buf_sizes); free(glyphs); free(ttf);
    return 0;
}

static void emit_c_string(ivo_buf_t *out, const char *s, size_t n)
{
    ivo_buf_puts(out, "\"");
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        switch (c) {
        case '\\': ivo_buf_puts(out, "\\\\"); break;
        case '"':  ivo_buf_puts(out, "\\\""); break;
        case '\n': ivo_buf_puts(out, "\\n\"\n    \""); break;
        case '\t': ivo_buf_puts(out, "\\t");  break;
        case '\r': ivo_buf_puts(out, "\\r");  break;
        case '?':  ivo_buf_puts(out, "\\?");  break;
        default:
            if (c < 0x20 || c > 0x7E) ivo_buf_printf(out, "\\%03o", c);
            else ivo_buf_append(out, (const char *)&c, 1);
        }
    }
    ivo_buf_puts(out, "\"");
}

static int cmd_mkinitivo(int argc, char **argv)
{
    const char *config_path = NULL;
    const char *output_path = NULL;
    for (int i = 0; i < argc; i++) {
        int v = i + 1 < argc;
        if      (strcmp(argv[i], "--config") == 0 && v) config_path = argv[++i];
        else if (strcmp(argv[i], "--output") == 0 && v) output_path = argv[++i];
        else {
            fprintf(stderr, "usage: ivo-build mkinitivo --config FILE --output FILE\n");
            return 1;
        }
    }
    if (!config_path || !output_path) {
        fprintf(stderr, "usage: ivo-build mkinitivo --config FILE --output FILE\n");
        return 1;
    }

    uint8_t *content = NULL;
    size_t len = 0;
    if (ivo_read_file(config_path, 1 << 20, &content, &len) != 0) {
        fprintf(stderr, "ivo-build: %s: %s\n", config_path, strerror(errno));
        return 1;
    }
    if (config_parse((const char *)content, len) != 0) {
        fprintf(stderr, "ivo-build: %s:%d: parse failed\n",
                config_path, config_error_line());
        free(content);
        return 1;
    }

    ivo_buf_t out = {0};
    ivo_buf_puts(&out, "/* Generated by tools/ivo-build mkinitivo. Do not edit. */\n"
                       "#ifndef EMBEDDED_CONFIG_H\n#define EMBEDDED_CONFIG_H\n\n"
                       "static const char ivo_embedded_config[] =\n    ");
    emit_c_string(&out, (const char *)content, len);
    ivo_buf_puts(&out, ";\n\n#endif\n");
    free(content);

    if (out.failed ||
        ivo_write_file(output_path, out.p, out.len, 0644,
                       IVO_WRITE_KEEP_MODE) != 0) {
        fprintf(stderr, "ivo-build: %s: %s\n", output_path,
                out.failed ? "out of memory" : strerror(errno));
        ivo_buf_free(&out);
        return 1;
    }
    ivo_buf_free(&out);
    return 0;
}

static void usage(void)
{
    fprintf(stderr,
        "usage:\n"
        "  ivo-build font INPUT.ttf LINE_HEIGHT BASELINE OUTPUT.h\n"
        "  ivo-build mkinitivo --config FILE --output FILE\n");
}

int main(int argc, char **argv)
{
    if (argc < 2) { usage(); return 1; }
    if (strcmp(argv[1], "font") == 0)      return cmd_font(argc - 2, argv + 2);
    if (strcmp(argv[1], "mkinitivo") == 0) return cmd_mkinitivo(argc - 2, argv + 2);
    usage();
    return 1;
}