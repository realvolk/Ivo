/* keymap_compiler — convert a keymap definition file into a C header.
 *
 * Input format:
 *   SCANCODE  CHARACTER
 *
 * Scancodes are hexadecimal. Characters are single ASCII bytes, or one
 * of \n \t \r \\, or a three-digit octal escape. # starts a comment.
 *
 * Usage: keymap_compiler us.txt > src/keymaps/us.h
 *
 * Not wired into the build. The headers in src/keymaps/ are
 * hand-written.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static int parse_char(const char *s, uint32_t *cp_out, const char **end_out)
{
    if (s[0] == '\\' && s[1] != 0) {
        switch (s[1]) {
        case 'n':  *cp_out = '\n'; *end_out = s + 2; return 0;
        case 't':  *cp_out = '\t'; *end_out = s + 2; return 0;
        case 'r':  *cp_out = '\r'; *end_out = s + 2; return 0;
        case '\\': *cp_out = '\\'; *end_out = s + 2; return 0;
        default:
            if (s[1] >= '0' && s[1] <= '7') {
                int v = 0;
                const char *p = s + 1;
                for (int i = 0; i < 3 && *p >= '0' && *p <= '7'; i++) {
                    v = v * 8 + (*p - '0');
                    p++;
                }
                *cp_out = (uint32_t)v;
                *end_out = p;
                return 0;
            }
            return -1;
        }
    }
    if (s[0] == 0) return -1;
    *cp_out = (unsigned char)s[0];
    *end_out = s + 1;
    return 0;
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: keymap_compiler <keymap.txt>\n");
        return 1;
    }

    FILE *in = fopen(argv[1], "r");
    if (!in) {
        fprintf(stderr, "keymap_compiler: %s: cannot read\n", argv[1]);
        return 1;
    }

    uint16_t table[256] = {0};
    int max_sc = 0;
    int line_no = 0;
    char line[256];

    while (fgets(line, sizeof(line), in)) {
        line_no++;

        if (!strchr(line, '\n') && !feof(in)) {
            fprintf(stderr, "%s:%d: line too long\n", argv[1], line_no);
            fclose(in);
            return 1;
        }

        char *hash = strchr(line, '#');
        if (hash) *hash = 0;

        char *s = line;
        while (*s == ' ' || *s == '\t') s++;
        char *end = s + strlen(s);
        while (end > s && (end[-1] == ' ' || end[-1] == '\t' ||
                           end[-1] == '\n' || end[-1] == '\r')) {
            end--;
        }
        *end = 0;
        if (*s == 0) continue;

        char *sc_str = s;
        char *ch_str = s;
        while (*ch_str && *ch_str != ' ' && *ch_str != '\t') ch_str++;
        if (*ch_str == 0) {
            fprintf(stderr, "%s:%d: missing character\n", argv[1], line_no);
            fclose(in);
            return 1;
        }
        *ch_str++ = 0;
        while (*ch_str == ' ' || *ch_str == '\t') ch_str++;

        char *endp = 0;
        long sc = strtol(sc_str, &endp, 16);
        if (*endp != 0 || sc < 0 || sc > 255) {
            fprintf(stderr, "%s:%d: bad scancode '%s'\n",
                    argv[1], line_no, sc_str);
            fclose(in);
            return 1;
        }

        uint32_t cp = 0;
        const char *ch_end = 0;
        if (parse_char(ch_str, &cp, &ch_end) != 0) {
            fprintf(stderr, "%s:%d: bad character\n", argv[1], line_no);
            fclose(in);
            return 1;
        }
        while (*ch_end == ' ' || *ch_end == '\t') ch_end++;
        if (*ch_end != 0) {
            fprintf(stderr, "%s:%d: trailing content\n", argv[1], line_no);
            fclose(in);
            return 1;
        }

        table[sc] = (uint16_t)cp;
        if (sc > max_sc) max_sc = sc;
    }
    fclose(in);

    int n = max_sc + 1;
    printf("/* Generated by tools/keymap_compiler. Do not edit. */\n");
    printf("static const uint16_t keymap[%d] = {\n", n);
    for (int i = 0; i < n; i++) {
        printf("    0x%04X,\n", table[i]);
    }
    printf("};\n");
    if (fflush(stdout) != 0 || ferror(stdout)) {
        fprintf(stderr, "keymap_compiler: write error\n");
        return 1;
    }
    return 0;
}