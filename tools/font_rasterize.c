#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <stdint.h>

#define STB_TRUETYPE_IMPLEMENTATION
#include "third_party/stb_truetype.h"

static const int FIRST_CHAR = 0x20;
static const int LAST_CHAR  = 0x7E;

struct glyph_out {
    uint32_t off;
    uint8_t  w;
    uint8_t  height;
    uint8_t  advance;
    int8_t   bx;
    int8_t   by;
};

int main(int argc, char **argv)
{
    if (argc != 5) {
        fprintf(stderr, "usage: %s <font.ttf> <line_height> <baseline> <out.h>\n",
                argv[0]);
        return 1;
    }
    const char *ttf_path = argv[1];
    int line_height      = atoi(argv[2]);
    int baseline         = atoi(argv[3]);
    const char *out_path = argv[4];

    FILE *f = fopen(ttf_path, "rb");
    if (!f) { perror(ttf_path); return 1; }
    fseek(f, 0, SEEK_END);
    long ttf_size = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *ttf = malloc((size_t)ttf_size);
    if (!ttf) { fclose(f); return 1; }
    if (fread(ttf, 1, (size_t)ttf_size, f) != (size_t)ttf_size) {
        fclose(f); free(ttf); return 1;
    }
    fclose(f);

    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, ttf, 0)) {
        fprintf(stderr, "InitFont failed\n");
        free(ttf);
        return 1;
    }

    float scale = stbtt_ScaleForPixelHeight(&info, (float)baseline);

    int count = LAST_CHAR - FIRST_CHAR + 1;
    struct glyph_out *glyphs = calloc(count, sizeof(*glyphs));
    uint8_t **bufs = calloc(count, sizeof(*bufs));
    int *buf_sizes = calloc(count, sizeof(*buf_sizes));

    /* Fixed advance for the whole font. Monospace, so every glyph
     * shares it. Uses 'M' as a representative. */
    int adv_ref = 0, lsb_ref = 0;
    stbtt_GetCodepointHMetrics(&info, 'M', &adv_ref, &lsb_ref);
    int advance_px = (int)(adv_ref * scale + 0.5f);
    if (advance_px < 1) advance_px = 1;
    if (advance_px > 255) advance_px = 255;
    int cell_w = advance_px;

    uint32_t total = 0;
    for (int i = 0; i < count; i++) {
        int cp = FIRST_CHAR + i;

        int x0, y0, x1, y1;
        stbtt_GetCodepointBitmapBox(&info, cp, scale, scale,
                                    &x0, &y0, &x1, &y1);
        int bw = x1 - x0;
        int bh = y1 - y0;
        if (bw < 0) bw = 0;
        if (bh < 0) bh = 0;

        glyphs[i].w       = (uint8_t)cell_w;
        glyphs[i].height  = (uint8_t)line_height;
        glyphs[i].bx      = 0;
        glyphs[i].by      = 0;
        glyphs[i].advance = (uint8_t)(advance_px * 4);
        glyphs[i].off     = total;

        size_t bytes = (size_t)line_height * cell_w;
        buf_sizes[i] = (int)bytes;
        bufs[i] = calloc(1, bytes);
        if (!bufs[i]) return 1;

        unsigned char *bmp = stbtt_GetCodepointBitmap(
            &info, scale, scale, cp, &bw, &bh, 0, 0);
        if (bmp) {
            for (int r = 0; r < line_height; r++) {
                int src_r = r - baseline - y0;
                if (src_r < 0 || src_r >= bh) continue;
                for (int c = 0; c < bw; c++) {
                    int dst_c = c + x0;
                    if (dst_c < 0 || dst_c >= cell_w) continue;
                    bufs[i][(size_t)r * cell_w + dst_c] = bmp[src_r * bw + c];
                }
            }
            stbtt_FreeBitmap(bmp, 0);
        }
        total += (uint32_t)bytes;
    }

    FILE *out = fopen(out_path, "w");
    if (!out) { perror(out_path); return 1; }
    fprintf(out, "/* Generated by tools/font_rasterize. Do not edit. */\n");
    fprintf(out, "#ifndef IVO_FONT_DATA_H\n#define IVO_FONT_DATA_H\n");
    fprintf(out, "#include \"ui/font.h\"\n\n");
    fprintf(out, "#define FONT_HEIGHT %d\n", line_height);
    fprintf(out, "#define FONT_BASELINE %d\n", baseline);
    fprintf(out, "#define FONT_FIRST_CHAR 0x%02X\n", FIRST_CHAR);
    fprintf(out, "#define FONT_GLYPH_COUNT %d\n\n", count);

    fprintf(out, "static const uint8_t font_data_raw[] = {\n");
    for (int i = 0; i < count; i++) {
        if (!bufs[i]) continue;
        for (int b = 0; b < buf_sizes[i]; b++) {
            if ((b % 16) == 0) fprintf(out, "    ");
            fprintf(out, "0x%02X,", bufs[i][b]);
            if ((b % 16) == 15) fprintf(out, "\n");
            else fprintf(out, " ");
        }
        if (buf_sizes[i] % 16) fprintf(out, "\n");
    }
    fprintf(out, "};\n\n");

    fprintf(out, "static const struct font_glyph font_glyphs_raw[] = {\n");
    for (int i = 0; i < count; i++) {
        fprintf(out, "    { %uu, %u, %u, %u, %d, %d },\n",
                glyphs[i].off, glyphs[i].w, glyphs[i].height,
                glyphs[i].advance,
                (int)glyphs[i].bx, (int)glyphs[i].by);
    }
    fprintf(out, "};\n\n");
    fprintf(out, "#endif\n");
    fclose(out);

    for (int i = 0; i < count; i++) free(bufs[i]);
    free(bufs); free(buf_sizes); free(glyphs); free(ttf);
    return 0;
}