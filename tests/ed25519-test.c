/* RFC 8032 Ed25519 verification test. Vectors from section 7.1. */

#include <stdio.h>
#include <string.h>
#include <stdint.h>

#include "crypto/ed25519.h"

static const uint8_t pk1[32] = {
    0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7,
    0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a,
    0x0e, 0xe1, 0x72, 0xf3, 0xda, 0xa6, 0x23, 0x25,
    0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a
};

static const uint8_t sig1[64] = {
    0xe5, 0x56, 0x43, 0x00, 0xc3, 0x60, 0xac, 0x72,
    0x90, 0x86, 0xe2, 0xcc, 0x80, 0x6e, 0x82, 0x8a,
    0x84, 0x87, 0x7f, 0x1e, 0xb8, 0xe5, 0xd9, 0x74,
    0xd8, 0x73, 0xe0, 0x65, 0x22, 0x49, 0x01, 0x55,
    0x5f, 0xb8, 0x82, 0x15, 0x90, 0xa3, 0x3b, 0xac,
    0xc6, 0x1e, 0x39, 0x70, 0x1c, 0xf9, 0xb4, 0x6b,
    0xd2, 0x5b, 0xf5, 0xf0, 0x59, 0x5b, 0xbe, 0x24,
    0x65, 0x51, 0x41, 0x43, 0x8e, 0x7a, 0x10, 0x0b
};

static const uint8_t pk2[32] = {
    0x3d, 0x40, 0x17, 0xc3, 0xe8, 0x43, 0x89, 0x5a,
    0x92, 0xb7, 0x0a, 0xa7, 0x4d, 0x1b, 0x7e, 0xbc,
    0x9c, 0x98, 0x2c, 0xcf, 0x2e, 0xc4, 0x96, 0x8c,
    0xc0, 0xcd, 0x55, 0xf1, 0x2a, 0xf4, 0x66, 0x0c
};

static const uint8_t sig2[64] = {
    0x92, 0xa0, 0x09, 0xa9, 0xf0, 0xd4, 0xca, 0xb8,
    0x72, 0x0e, 0x82, 0x0b, 0x5f, 0x64, 0x25, 0x40,
    0xa2, 0xb2, 0x7b, 0x54, 0x16, 0x50, 0x3f, 0x8f,
    0xb3, 0x76, 0x22, 0x23, 0xeb, 0xdb, 0x69, 0xda,
    0x08, 0x5a, 0xc1, 0xe4, 0x3e, 0x15, 0x99, 0x6e,
    0x45, 0x8f, 0x36, 0x13, 0xd0, 0xf1, 0x1d, 0x8c,
    0x38, 0x7b, 0x2e, 0xae, 0xb4, 0x30, 0x2a, 0xee,
    0xb0, 0x0d, 0x29, 0x16, 0x12, 0xbb, 0x0c, 0x00
};

int main(void)
{
    int ok1 = ed25519_verify(sig1, (const unsigned char *)"", 0, pk1);
    printf("vector 1 (empty msg): %s\n", ok1 ? "OK" : "FAIL");

    const uint8_t msg2 = 0x72;
    int ok2 = ed25519_verify(sig2, &msg2, 1, pk2);
    printf("vector 2 (0x72):      %s\n", ok2 ? "OK" : "FAIL");

    uint8_t bad_sig[64];
    memcpy(bad_sig, sig1, 64);
    bad_sig[0] ^= 0x01;
    int ok3 = ed25519_verify(bad_sig, (const unsigned char *)"", 0, pk1);
    printf("negative (flip sig):  %s\n", ok3 ? "FAIL" : "OK");

    /* S + L: same scalar mod L, non-canonical encoding. Accepted by
     * a verifier that only checks the top three bits. */
    static const uint8_t L[32] = {
        0xed, 0xd3, 0xf5, 0x5c, 0x1a, 0x63, 0x12, 0x58,
        0xd6, 0x9c, 0xf7, 0xa2, 0xde, 0xf9, 0xde, 0x14,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10
    };
    memcpy(bad_sig, sig1, 64);
    unsigned carry = 0;
    for (int i = 0; i < 32; i++) {
        unsigned v = bad_sig[32 + i] + L[i] + carry;
        bad_sig[32 + i] = (uint8_t)v;
        carry = v >> 8;
    }
    int ok4 = ed25519_verify(bad_sig, (const unsigned char *)"", 0, pk1);
    printf("negative (S + L):     %s\n", ok4 ? "FAIL" : "OK");

    memcpy(bad_sig, sig1, 64);
    bad_sig[63] |= 0x80;
    int ok5 = ed25519_verify(bad_sig, (const unsigned char *)"", 0, pk1);
    printf("negative (S high):    %s\n", ok5 ? "FAIL" : "OK");

    int ok6 = ed25519_verify(sig1, (const unsigned char *)"", 0, pk2);
    printf("negative (wrong pk):  %s\n", ok6 ? "FAIL" : "OK");

    int ok7 = ed25519_verify(sig2, &msg2, 0, pk2);
    printf("negative (truncated): %s\n", ok7 ? "FAIL" : "OK");

    const uint8_t msg2x[2] = { 0x72, 0x00 };
    int ok8 = ed25519_verify(sig2, msg2x, 2, pk2);
    printf("negative (extended):  %s\n", ok8 ? "FAIL" : "OK");

    if (!ok1 || !ok2 || ok3 || ok4 || ok5 || ok6 || ok7 || ok8) return 1;
    printf("all pass\n");
    return 0;
}
